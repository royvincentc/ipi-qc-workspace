import {chromium} from 'playwright';
import {mkdir, writeFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
const out = 'tmp/redesign-review';
await mkdir(out, {recursive:true});
const browser = await chromium.launch({channel:'msedge', headless:true});
const page = await browser.newPage({viewport:{width:1440,height:1000}});
const errors = [];
const checks = [];
page.on('pageerror', error => errors.push(error.message));
const capture = async name => {
  await page.evaluate(() => document.fonts.ready);
  await page.evaluate(() => {window.scrollTo(0,0); if(document.activeElement instanceof HTMLElement)document.activeElement.blur();});
  if (name === 'overview-populated') await page.waitForTimeout(1300);
  await page.screenshot({path:`${out}/${name}.png`,fullPage:true,animations:'disabled'});
  const dimensions = await page.evaluate(() => ({width:innerWidth,scroll:document.documentElement.scrollWidth}));
  checks.push({name,...dimensions});
  assert.ok(dimensions.scroll <= dimensions.width+1, `${name}: page overflow ${dimensions.scroll}`);
};
await page.goto('http://localhost:5173/');
await page.getByRole('heading', {name:'Laboratory overview', exact:true}).waitFor();
await page.getByRole('region', {name:'Sample log, scroll for more records and columns'}).getAttribute('aria-busy');
await page.waitForFunction(() => document.querySelector('.reception-table-scroll')?.getAttribute('aria-busy') === 'false');
await capture('overview-desktop');
console.log('dashboard', await page.locator('.operations-summary').innerText());
await page.getByRole('button',{name:'Previous month',exact:true}).click();
await page.waitForFunction(() => document.querySelector('.reception-table-scroll')?.getAttribute('aria-busy') === 'false' && document.querySelector('.reception-total-number')?.textContent?.includes('September'));
assert.match(await page.locator('.reception-total-number').innerText(), /7/);
await capture('overview-populated');
await page.getByRole('group',{name:'Explore daily receipts'}).getByRole('button',{name:/23 Sept: 7 samples/}).click();
await page.waitForFunction(() => document.querySelector('.reception-table-scroll')?.getAttribute('aria-busy') === 'false');
assert.equal(await page.locator('.reception-selected-day').count(),1);
await page.getByRole('button',{name:/Clear selected day/}).click();
await page.getByRole('textbox',{name:'Search sample log'}).fill('Demo Product A');
await page.waitForResponse(r=>r.url().includes('/api/reception?') && r.url().includes('q=Demo'));
await page.getByRole('button',{name:'Clear sample search'}).click();
await page.keyboard.press('Control+k');
await page.getByRole('dialog').waitFor();
await page.getByRole('textbox',{name:'Find a sample anywhere'}).fill('ML');
await page.keyboard.press('Escape');
assert.equal(await page.getByRole('dialog').count(),0);
await page.getByRole('button',{name:'Switch to dark theme',exact:true}).click();
await capture('overview-dark');
await page.getByRole('button',{name:'Switch to light theme',exact:true}).click();
for (const [route,name] of [['new','intake'],['samples','samples'],['samples/demo-FG','sample-detail'],['worksheet','worksheet'],['reports','reports'],['library','library'],['shared','shared'],['assistant','assistant'],['settings','settings']]) {
  await page.goto(`http://localhost:5173/${route}`);
  await page.locator('#workspace-main').waitFor();
  await page.waitForLoadState('networkidle');
  await capture(`${name}-desktop`);
  await page.setViewportSize({width:390,height:844});
  await capture(`${name}-mobile`);
  await page.setViewportSize({width:1440,height:1000});
}
await page.goto('http://localhost:5173/login');
await page.getByRole('heading', {name:'Welcome to Micro-QC.'}).waitFor();
await capture('login-desktop');
await page.setViewportSize({width:390,height:844});
await capture('login-mobile');
await page.route('**/api/me',route=>route.fulfill({status:401,json:{error:'Sign in to access the workspace'}}));
await page.reload();
await page.getByRole('link',{name:'Sign in with Google'}).waitFor();
await capture('login-signin-mobile');
await page.unroute('**/api/me');
await page.goto('http://localhost:5173/');
await page.getByRole('heading', {name:'Laboratory overview', exact:true}).waitFor();
await page.waitForFunction(() => document.querySelector('.reception-table-scroll')?.getAttribute('aria-busy') === 'false');
await capture('overview-mobile');
await page.getByRole('button',{name:'Open navigation',exact:true}).click();
await page.locator('.sidebar.mobile-open').waitFor();
await capture('navigation-mobile');
await page.getByRole('button',{name:'Switch to dark theme',exact:true}).click();
assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
await page.getByRole('button',{name:'Switch to light theme',exact:true}).click();
await page.getByRole('button',{name:/Open global sample search/}).click();
await page.getByRole('dialog').waitFor();
await page.getByRole('textbox',{name:'Find a sample anywhere'}).fill('ML');
await page.keyboard.press('Escape');
await page.emulateMedia({reducedMotion:'reduce'});
assert.equal(await page.locator('.route-stage').evaluate(el=>getComputedStyle(el).animationName),'none');
console.log('overflow', await page.evaluate(() => ({width:innerWidth,scroll:document.documentElement.scrollWidth})));
await writeFile(`${out}/verification.json`,JSON.stringify({checks,errors},null,2));
console.log(JSON.stringify({checks,errors},null,2));
assert.equal(errors.length,0);
await browser.close();
