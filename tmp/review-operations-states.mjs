import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';
const out='tmp/redesign-review';
await mkdir(out,{recursive:true});
const browser=await chromium.launch({channel:'msedge',headless:true});
const context=await browser.newContext({viewport:{width:1440,height:1000},recordVideo:{dir:`${out}/recordings`,size:{width:1280,height:800}}});
const page=await context.newPage();
const errors=[], checks=[];
page.on('pageerror',e=>errors.push(e.message));
const go=async path=>{await page.goto(`http://localhost:5173${path}`);await page.waitForLoadState('networkidle');};
const shot=async name=>{await page.evaluate(()=>document.fonts.ready);await page.screenshot({path:`${out}/${name}.png`,fullPage:true,animations:'disabled'});checks.push(name);};
await go('/');
const {sample}=await page.request.get('http://localhost:5173/api/samples/demo-FG').then(r=>r.json());
let draft={id:'visual-fixture',sampleId:sample.id,sample,specification:{id:'visual-spec',product:sample.name,category:'FG',context:'Routine',revision:'fixture',issues:[],source:'Browser fixture',tests:[{test:'SPC',label:'Standard Plate Count',type:'numeric',unit:'cfu/mL',criterion:'Nmt 100 cfu/mL',source:'Browser fixture',sourceLocation:'Fixture',date:'2026-09-23',dateBasis:'analysis',revision:'fixture'}]},templateId:'visual-template',templateRevision:'fixture',templateSnapshot:{id:'visual-template',name:'Browser fixture',category:'FG',family:'product',revision:'fixture',verified:true,manifest:{tokens:[],requiredFields:[]}},revision:1,results:[{test:'SPC',state:'not_entered',value:'',qualifier:'',unit:'cfu/mL',reason:'',remarks:''}],fields:{analysisDate:'09/23/2026'},updatedAt:'2026-09-23T09:00:00Z',analyst:'Demo Analyst'};
await page.route('**/api/drafts/visual-fixture',async route=>{
  if(route.request().method()==='PUT')draft={...draft,...route.request().postDataJSON(),revision:draft.revision+1};
  await route.fulfill({json:draft});
});
await page.route('**/api/drafts/visual-fixture/report-details',route=>route.fulfill({json:{optionalFields:[],incompleteCC:[]}}));
await go('/reports/visual-fixture');
await shot('report-editor-desktop');
await page.setViewportSize({width:390,height:844});
await shot('report-editor-mobile');
await page.setViewportSize({width:1440,height:1000});
await page.getByRole('button',{name:'Review report',exact:true}).click();
await shot('report-review-validation');
await go('/new');
await page.getByRole('button',{name:/Finished Goods/}).filter({hasText:/^Finished Goods/}).click();
await shot('intake-form-desktop');
await page.setViewportSize({width:390,height:844});
await shot('intake-form-mobile');
await page.setViewportSize({width:1440,height:1000});
await go('/worksheet');
await page.getByRole('button',{name:/^Add workspace note for/}).first().click();
await shot('worksheet-note');
await page.keyboard.press('Escape');
await go('/');
await page.waitForFunction(()=>document.querySelector('.reception-table-scroll')?.getAttribute('aria-busy')==='false');
await page.route('**/api/reception?**',route=>route.fulfill({status:503,json:{error:'Receipts temporarily unavailable'}}));
await page.evaluate(()=>window.dispatchEvent(new Event('ipi:sync-complete')));
await page.getByRole('button',{name:'Retry receipts',exact:true}).waitFor();
assert.match(await page.locator('.operations-stat').first().innerText(), /\u2014/);
assert.equal(await page.getByText('No dated receipts this month',{exact:true}).count(),0);
await shot('receipts-error');
await page.unroute('**/api/reception?**');
await page.getByRole('button',{name:'Retry receipts',exact:true}).click();
await page.waitForFunction(()=>document.querySelector('.reception-table-scroll')?.getAttribute('aria-busy')==='false');
assert.match(await page.locator('.reception-total-number').innerText(),/0/);
checks.push('receipt retry recovers');
const current=await page.request.get('http://localhost:5173/api/me').then(r=>r.json());
await page.route('**/api/me',route=>route.fulfill({json:{...current,user:{...current.user,role:'viewer'}}}));
await go('/settings');
await page.getByText('Administrator access required',{exact:true}).waitFor();
await shot('viewer-settings-denied');
assert.equal(await page.locator('.utility-nav').getByRole('link',{name:'Log a sample',exact:true}).count(),0);
assert.equal(await page.locator('.sidebar').getByRole('link',{name:'Settings',exact:true}).count(),0);
await page.unroute('**/api/me');
await page.route('**/api/me',route=>route.fulfill({status:503,json:{error:'Laboratory API temporarily unavailable'}}));
await go('/');
await page.getByRole('button',{name:'Retry connection',exact:true}).waitFor();
await shot('login-connection-error');
await page.unroute('**/api/me');
await page.getByRole('button',{name:'Retry connection',exact:true}).click();
await page.getByRole('heading',{name:'Laboratory overview',exact:true}).waitFor();
checks.push('connection retry recovers');
await go('/?preview=login');
await page.getByRole('heading',{name:'Laboratory overview',exact:true}).waitFor();
checks.push('unrelated query does not activate login');
await page.getByRole('navigation',{name:'Main destinations'}).getByRole('link',{name:'Samples',exact:true}).click();
await page.goBack();
await page.getByRole('heading',{name:'Laboratory overview',exact:true}).waitFor();
checks.push('browser back restores overview');
await page.getByRole('button',{name:'Switch to dark theme',exact:true}).click();
await page.reload();
await page.getByRole('heading',{name:'Laboratory overview',exact:true}).waitFor();
assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
await page.getByRole('button',{name:'Switch to light theme',exact:true}).click();
checks.push('theme persists after refresh');
await shot('overview-final');
await context.close();
await browser.close();
await writeFile(`${out}/states.json`,JSON.stringify({checks,errors},null,2));
console.log(JSON.stringify({checks,errors},null,2));
assert.equal(errors.length,0);
