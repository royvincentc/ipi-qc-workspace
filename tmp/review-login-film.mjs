import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {mkdir,writeFile,copyFile} from 'node:fs/promises';

const out='tmp/redesign-review/login-film';
await mkdir(out,{recursive:true});
const browser=await chromium.launch({channel:'msedge',headless:true});
const context=await browser.newContext({viewport:{width:1440,height:900},reducedMotion:'no-preference',recordVideo:{dir:out,size:{width:1440,height:900}}});
const page=await context.newPage();
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
const checks=[];
const check=(name)=>checks.push(name);
const overflow=async()=>{
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'horizontal overflow');
  if(await page.locator('.login-screen').count()){
    const stage=await page.locator('.login-film-stage').boundingBox();
    const control=await page.locator('.login-film-control').boundingBox();
    assert.ok(control.y>=stage.y+stage.height-1,'Playback control must sit below artwork');
  }
};
await page.goto('http://127.0.0.1:5174/login');
await page.getByRole('link',{name:'Enter laboratory workspace'}).waitFor();
await page.evaluate(()=>document.fonts.ready);
const svg=()=>page.locator('.login-film-stage svg').innerHTML();
await page.locator('.login-film-stage svg').waitFor();
await page.waitForTimeout(300);
const before=await svg();
await page.waitForTimeout(250);
assert.notEqual(await svg(),before);
await overflow();
await page.screenshot({path:`${out}/login-desktop.png`});
check('Desktop: microbiology SVG Remotion film plays and advances, no horizontal overflow');
await page.getByRole('button',{name:'Pause background video'}).click();
const paused=await svg();
await page.waitForTimeout(250);
assert.equal(await svg(),paused);
await page.getByRole('button',{name:'Play background video'}).press('Enter');
await page.waitForTimeout(350);
assert.notEqual(await svg(),paused);
check('Pause freezes video; keyboard resumes it');
await page.getByRole('link',{name:'Enter laboratory workspace'}).click();
await page.locator('.login-arrival').waitFor();
assert.equal(await page.locator('.workspace-arrival-content').evaluate(el=>el.inert),true);
const arrivalSvg=page.locator('.login-arrival svg').first();
await arrivalSvg.waitFor();
const arrivalBefore=await arrivalSvg.innerHTML();
await page.waitForTimeout(550);
assert.notEqual(await arrivalSvg.innerHTML(),arrivalBefore,'Remotion arrival SVG advances');
assert.equal(await page.locator('.workspace-arrival-content').evaluate(el=>el.inert),true);
await page.screenshot({path:`${out}/workspace-reveal.png`});
await page.locator('.login-arrival').waitFor({state:'detached',timeout:5000});
await page.getByRole('heading',{name:'Laboratory overview',exact:true}).waitFor();
assert.equal(await page.locator('.workspace-arrival-content').evaluate(el=>el.inert),false);
assert.equal(await page.evaluate(()=>document.activeElement.id),'workspace-main');
assert.equal(await page.evaluate(()=>sessionStorage.getItem('ipi.login.handoff')),null);
await page.reload();
await page.getByRole('heading',{name:'Laboratory overview',exact:true}).waitFor();
assert.equal(await page.locator('.login-arrival').count(),0);
check('Demo entry plays microbiology SVG Remotion arrival (~1200ms); covered controls inert; focus transferred; marker consumed; reload does not replay');

let signedIn=false;
await page.route('**/api/me',route=>signedIn?route.continue():route.fulfill({status:401,json:{error:'Sign in to access the workspace'}}));
await page.route('**/api/auth/login',route=>{signedIn=true;return route.fulfill({status:302,headers:{location:'/'}});});
await page.goto('http://127.0.0.1:5174/login');
await page.getByRole('link',{name:'Sign in with Google',exact:true}).waitFor();
await page.screenshot({path:`${out}/login-google-desktop.png`});
await page.setViewportSize({width:390,height:844});
await overflow();
await page.screenshot({path:`${out}/login-google-mobile.png`,fullPage:true});
await page.getByRole('button',{name:'Pause background video'}).click();
assert.equal(await page.locator('.login-film').evaluate(el=>el.classList.contains('is-paused')),true);
await page.getByRole('button',{name:'Play background video'}).click();
await page.getByRole('link',{name:'Sign in with Google',exact:true}).click();
await page.locator('.login-arrival').waitFor();
await page.getByRole('button',{name:'Skip animation',exact:true}).click();
await page.locator('.login-arrival').waitFor({state:'detached'});
await page.getByRole('heading',{name:'Laboratory overview',exact:true}).waitFor();
assert.equal(await page.locator('.workspace-arrival-content').evaluate(el=>el.inert),false);
assert.equal(await page.evaluate(()=>document.activeElement.id),'workspace-main');
assert.equal(await page.evaluate(()=>sessionStorage.getItem('ipi.login.handoff')),null);
await overflow();
await page.screenshot({path:`${out}/dashboard-after-mobile-entry.png`});
await page.setViewportSize({width:1440,height:900});
check('Browser-only OAuth redirect simulation: Google link -> fresh document -> confirmed /me -> skippable dashboard reveal');

await page.unroute('**/api/me');
await page.route('**/api/me',route=>route.fulfill({status:503,json:{error:'Unable to connect to laboratory API'}}));
await page.evaluate(()=>sessionStorage.setItem('ipi.login.handoff',String(Date.now())));
await page.goto('http://127.0.0.1:5174/login');
await page.getByRole('button',{name:'Retry connection'}).waitFor();
assert.equal(await page.locator('.login-arrival').count(),0);
await page.unroute('**/api/me');
await page.getByRole('button',{name:'Retry connection'}).click();
await page.getByRole('link',{name:'Enter laboratory workspace'}).click();
await page.getByRole('heading',{name:'Laboratory overview',exact:true}).waitFor();
await page.locator('.login-arrival').waitFor({state:'detached'});
check('Connection failure on /login remains recoverable; pending intent never grants access');

await page.route('**/api/configuration',route=>route.fulfill({status:503,json:{error:'Settings unavailable'}}));
await page.evaluate(()=>sessionStorage.setItem('ipi.login.handoff',String(Date.now())));
await page.reload();
await page.getByRole('alert').filter({hasText:'Settings unavailable'}).waitFor();
assert.equal(await page.locator('.login-arrival').count(),0);
await page.unroute('**/api/configuration');
await page.getByRole('button',{name:'Try again',exact:true}).click();
await page.getByRole('heading',{name:'Laboratory overview',exact:true}).waitFor();
await page.locator('.login-arrival').waitFor({state:'detached'});
check('Settings failure stays recoverable; reveal waits for authenticated workspace configuration');

let releaseConnection;
const connectionGate=new Promise(resolve=>{releaseConnection=resolve;});
await page.route('**/api/me',async route=>{await connectionGate;await route.continue();});
await page.evaluate(()=>sessionStorage.setItem('ipi.login.handoff',String(Date.now())));
await page.reload({waitUntil:'domcontentloaded'});
await page.getByRole('status').filter({hasText:'Connecting to your workspace'}).waitFor();
await page.getByRole('button',{name:'Pause background video'}).click();
assert.equal(await page.locator('.login-film').evaluate(el=>el.classList.contains('is-paused')),true);
releaseConnection();
await page.getByRole('heading',{name:'Laboratory overview',exact:true}).waitFor();
await page.locator('.login-arrival').waitFor({state:'detached'});
await page.unroute('**/api/me');
check('A stalled session check keeps a usable pause control and recovers after response');

await page.evaluate(()=>sessionStorage.setItem('ipi.login.handoff',String(Date.now()-11*60_000)));
await page.reload();
await page.getByRole('heading',{name:'Laboratory overview',exact:true}).waitFor();
assert.equal(await page.locator('.login-arrival').count(),0);
check('Expired handoff does not replay');
await page.emulateMedia({reducedMotion:'reduce'});
await page.goto('http://127.0.0.1:5174/login');
await page.getByRole('link',{name:'Enter laboratory workspace'}).waitFor();
assert.equal(await page.locator('.login-film').evaluate(el=>el.classList.contains('is-paused')),true);
await page.getByRole('link',{name:'Enter laboratory workspace'}).click();
await page.getByRole('heading',{name:'Laboratory overview',exact:true}).waitFor();
assert.equal(await page.locator('.login-arrival').isVisible(),false);
check('Reduced motion uses a fixed frame and immediate dashboard access');

for(const width of [320,768]){
  await page.setViewportSize({width,height:900});
  await page.goto('http://127.0.0.1:5174/login');
  await page.getByRole('link',{name:'Enter laboratory workspace'}).waitFor();
  await overflow();
}
check('Narrow mobile and tablet: no overflow and playback controls remain outside artwork');

await page.emulateMedia({reducedMotion:'no-preference'});
await page.addInitScript(()=>Object.defineProperty(window,'sessionStorage',{get(){throw new Error('Storage disabled');}}));
await page.goto('http://127.0.0.1:5174/login');
await page.getByRole('link',{name:'Enter laboratory workspace'}).click();
await page.getByRole('heading',{name:'Laboratory overview',exact:true}).waitFor();
check('Blocked session storage does not break entry');
assert.deepEqual(errors,[]);
const recording=page.video();
await context.close();
await copyFile(await recording.path(),`${out}/login-to-dashboard.webm`);
await browser.close();
await writeFile(`${out}/checks.json`,JSON.stringify({checks,pageErrors:errors,realGoogleOAuth:'Not performed; redirect simulation uses browser interception only'},null,2));
console.log(JSON.stringify(checks,null,2));
